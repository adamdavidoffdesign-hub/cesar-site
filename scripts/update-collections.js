const update = db.prepare(`
  UPDATE collections
  SET name = ?, designer = ?, description = ?, page_content = ?, updated_at = CURRENT_TIMESTAMP
  WHERE slug = ?
`);

Object.entries(collections).forEach(([slug, data]) => {
  const result = update.run(
    data.name,
    data.designer,
    JSON.stringify(data.description),
    JSON.stringify(data.page_content),
    slug
  );
  if (result.changes > 0) {
    console.log(`✓ ${slug} — обновлено`);
  } else {
    console.warn(`✗ ${slug} — не найдено в БД`);
  }
});

console.log('\nГотово.');
